#!/usr/bin/env bash
# fetch-reference.sh — download bergamot-translator, the reference engine.
#
# SPEC §13 T4 needs a number to be measured *against*. This is that number's
# source: the actual Bergamot engine, run in-process over the actual model
# files, rather than a published score for a build nobody here can inspect.
#
# The Emscripten glue declares `var Module` at top level, which hoists and
# shadows anything a caller sets on `globalThis`. Prepending our own `var
# Module` makes the module's own `typeof Module != "undefined"` guard find it.
set -euo pipefail

DIR="$(cd "$(dirname "$0")" && pwd)/reference"
BASE="https://github.com/browsermt/bergamot-translator/releases/download/latest"

mkdir -p "$DIR"
for f in bergamot-translator-worker.js bergamot-translator-worker.wasm; do
  if [ ! -s "$DIR/$f" ]; then
    echo "  fetching $f"
    curl -sSL -o "$DIR/$f" "$BASE/$f"
  fi
done

{
  cat <<'PREAMBLE'
// GENERATED by tools/eval/fetch-reference.sh — do not edit.
var Module = {
  wasmBinary: require("fs").readFileSync(__dirname + "/bergamot-translator-worker.wasm"),
  print: function () {},
  printErr: function () {},
};
PREAMBLE
  cat "$DIR/bergamot-translator-worker.js"
  echo 'module.exports = Module;'
} > "$DIR/engine.cjs"

node -e "
const M = require('$DIR/engine.cjs');
new Promise(r => { M.onRuntimeInitialized = r; }).then(() => {
  for (const k of ['TranslationModel','BlockingService','AlignedMemory'])
    if (!M[k]) { console.error('missing ' + k); process.exit(1); }
  console.log('  reference engine ready (' + (globalThis.BERGAMOT_VERSION_FULL || 'bergamot-translator') + ')');
});
"
